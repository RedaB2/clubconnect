-- Privileged psql, ON_ERROR_STOP=1. Synthetic identities and private data are rolled back.
begin;
set local plpgsql.check_asserts=on;
do $test$
declare
    owner uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid(); alum uuid:=gen_random_uuid(); orphan uuid:=gen_random_uuid();
    c uuid:=gen_random_uuid(); other uuid:=gen_random_uuid(); closed uuid:=gen_random_uuid();
    app uuid; prior uuid; direct_message uuid:=gen_random_uuid(); info jsonb; item jsonb; profile jsonb; address text;
begin
    foreach address in array array['a,b@example.org','a;b@example.org','a:b@example.org','a..b@example.org',
                                    '.bad@example.org','bad.@example.org','Name <person@example.org>','a@b..org'] loop
        assert public.before_usc_signup(jsonb_build_object('user',jsonb_build_object('email',address)))->'error'->>'http_code'='403';
    end loop;
    assert public.before_usc_signup('{"user":{"email":"former+club@example.org"}}')='{}'::jsonb;
    assert public.before_usc_signup('{"user":{"email":"former@example.org","is_anonymous":true}}')->'error'->>'http_code'='403';
    assert public.before_usc_signup('{"user":{"email":"former@example.org","app_metadata":{"provider":"apple"}}}')->'error'->>'http_code'='403';
    insert into auth.users(id,email,email_confirmed_at,raw_app_meta_data) values
        (owner,owner||'@usc.edu',now(),'{"provider":"email"}'),(outsider,outsider||'@usc.edu',now(),'{"provider":"email"}'),
        (alum,alum||'@example.invalid',null,'{"provider":"email"}'),(orphan,orphan||'@dept.usc.edu',now(),'{"provider":"email"}');
    perform set_config('request.jwt.claims',jsonb_build_object('sub',owner,'role','authenticated')::text,true);
    set local role authenticated;
    perform public.create_campus_club(c,'Application fixture A','{"name":"Organizer","graduationTerm":"spring","graduationYear":2000}');
    perform public.create_campus_club(closed,'Closed fixture');
    perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
    perform public.create_campus_club(other,'Application fixture B','{"name":"Second organizer","graduationTerm":"spring","graduationYear":2002}');
    reset role;
    update club_private.clubs set open_enrollment=false where id=closed::text;
    update club_private.clubs set about=repeat('a',450) where id=c::text;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',alum,'role','authenticated')::text,true);
    set local role authenticated;
    begin perform public.alumni_workspace(); raise exception 'Unverified account reached workspace';
    exception when invalid_authorization_specification then null; end;
    reset role;
    update auth.users set email_confirmed_at=now() where id=alum;
    set local role authenticated;
    info:=public.alumni_workspace(); assert info->'profile'='null'::jsonb and info->'catalog'='[]'::jsonb and info->'applications'='[]'::jsonb;
    begin perform public.request_alumni_membership(c::text,'test'); raise exception 'Admission started without alumni profile';
    exception when insufficient_privilege then null; end;
    begin perform public.save_alumni_profile(jsonb_build_object('name','Test','graduationTerm','fall','graduationYear',extract(year from now())::integer+1));
        raise exception 'Future graduation accepted';
    exception when invalid_parameter_value then null; end;
    profile:=jsonb_build_object('name','Alumni Fixture','graduationTerm','spring','graduationYear',2005,'major','Architecture',
                                 'interests',jsonb_build_array('Film'),'bio','A short biography','photoData','eA==');
    perform public.save_alumni_profile(profile||jsonb_build_object('id',owner,'admin',true,'kind','student'));
    perform public.save_alumni_profile('{"name":"Updated Alum","graduationTerm":"fall","graduationYear":2005}');
    info:=public.alumni_workspace();
    assert info->'profile'->>'id'=alum::text and info->'profile'->>'kind'='alumni' and
           info->'profile'->>'major'='Architecture' and info->'profile'->>'photoData'='eA==';
    select x into strict item from jsonb_array_elements(info->'catalog') x where x->'club'->>'id'=c::text;
    assert not (item->>'joined')::boolean and not(item ? 'pendingRequestCount') and
           not(item->'club' ? 'members') and not(item->'club' ? 'logoData') and length(item->'club'->>'about')=300;
    assert not exists(select from jsonb_array_elements(info->'catalog') x where x->'club'->>'id'=closed::text);
    begin perform public.request_alumni_membership(closed::text); raise exception 'Requested unlisted club';
    exception when insufficient_privilege then null; end;
    begin perform public.request_alumni_membership(c::text,repeat('a',301)); raise exception 'Overlong admission note';
    exception when invalid_parameter_value then null; end;
    begin perform public.enroll_student(c::text,'Former','spring',2000); raise exception 'Legacy personal enrollment bypass';
    exception when insufficient_privilege then null; end;
    begin perform public.join_additional(c::text); raise exception 'Direct enrollment bypass';
    exception when insufficient_privilege then null; end;
    begin perform public.create_campus_club(gen_random_uuid(),'Personal club'); raise exception 'Personal-created campus club';
    exception when insufficient_privilege then null; end;
    begin perform public.verify_wallet_member(); raise exception 'Sample Wallet allowed personal identity';
    exception when insufficient_privilege then null; end;
    begin perform public.invite_alumnus(c::text,'legacy@example.invalid'); raise exception 'Legacy invitation endpoint available';
    exception when insufficient_privilege then null; end;
    perform public.request_alumni_membership(c::text,'  Events committee  ');
    perform public.request_alumni_membership(c::text,'Retry');
    perform public.request_alumni_membership(other::text);
    info:=public.alumni_workspace();
    assert jsonb_array_length(info->'applications')=2;
    select x into strict item from jsonb_array_elements(info->'applications') x where x->>'clubID'=c::text;
    app:=(item->>'id')::uuid; assert item->>'note'='Events committee' and item->>'status'='pending';
    begin perform public.snapshot(c::text); raise exception 'Pending request loaded roster';
    exception when insufficient_privilege then null; end;
    begin perform public.message_inbox(c::text); raise exception 'Pending request loaded inbox';
    exception when insufficient_privilege then null; end;
    assert not club_private.can_listen_to_mailbox('mail:'||alum||':'||c);
    begin perform public.review_alumni_applications(c::text); raise exception 'Applicant saw organizer queue';
    exception when insufficient_privilege then null; end;
    begin perform public.decide_alumni_application(c::text,app,true); raise exception 'Applicant approved themself';
    exception when insufficient_privilege then null; end;
    reset role;
    update club_private.clubs set open_enrollment=false where id=c::text;
    set local role authenticated;
    select x into strict item from jsonb_array_elements(public.club_catalog()) x where x->'club'->>'id'=c::text;
    assert not(item->>'canJoin')::boolean and not(item->>'joined')::boolean and not(item->'club' ? 'logoData');
    perform public.withdraw_alumni_request(c::text);
    begin perform public.request_alumni_membership(c::text); raise exception 'Could reapply to closed admissions';
    exception when insufficient_privilege then null; end;
    reset role;
    update club_private.clubs set open_enrollment=true where id=c::text;
    set local role authenticated;
    perform public.withdraw_alumni_request(c::text);
    perform public.withdraw_alumni_request(c::text);
    perform public.request_alumni_membership(c::text,'New request');
    prior:=app;
    select (x->>'id')::uuid into strict app from jsonb_array_elements(public.alumni_workspace()->'applications') x where x->>'clubID'=c::text;
    assert app<>prior;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',owner,'role','authenticated')::text,true);
    begin perform public.decide_alumni_application(c::text,prior,true); raise exception 'Decided a withdrawn request';
    exception when invalid_parameter_value then null; end;
    begin perform public.decide_alumni_application(other::text,app,true); raise exception 'Applied decision to a different club';
    exception when insufficient_privilege then null; end;
    assert jsonb_array_length(public.review_alumni_applications(c::text))=2;
    begin perform public.review_alumni_applications(other::text); raise exception 'Organizer saw independent club requests';
    exception when insufficient_privilege then null; end;
    assert exists(select from jsonb_array_elements(public.club_catalog()) x where x->'club'->>'id'=c::text and (x->>'pendingRequestCount')::integer=1);
    perform public.decide_alumni_application(c::text,app,false);
    perform public.decide_alumni_application(c::text,app,false);
    begin perform public.decide_alumni_application(c::text,app,true); raise exception 'Conflicting final decision allowed';
    exception when invalid_parameter_value then null; end;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
    begin perform public.review_alumni_applications(c::text); raise exception 'Unrelated campus user saw private applicant';
    exception when insufficient_privilege then null; end;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',alum,'role','authenticated')::text,true);
    assert exists(select from jsonb_array_elements(public.alumni_workspace()->'applications') x where x->>'clubID'=c::text and x->>'status'='declined');
    begin perform public.snapshot(c::text); raise exception 'Declined applicant loaded roster';
    exception when insufficient_privilege then null; end;
    perform public.request_alumni_membership(c::text,'Reapplying after a decline');
    prior:=app;
    select (x->>'id')::uuid into strict app from jsonb_array_elements(public.alumni_workspace()->'applications') x where x->>'clubID'=c::text;
    assert app<>prior;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',owner,'role','authenticated')::text,true);
    perform public.decide_alumni_application(c::text,app,true);
    perform public.decide_alumni_application(c::text,app,true);
    assert jsonb_array_length(public.review_alumni_applications(c::text))=3;
    assert exists(select from jsonb_array_elements(public.club_catalog()) x where x->'club'->>'id'=c::text and (x->>'pendingRequestCount')::integer=0);
    begin perform public.step_down(c::text,alum); raise exception 'Personal-email member promoted';
    exception when insufficient_privilege then null; end;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',alum,'role','authenticated')::text,true);
    info:=public.snapshot(c::text); assert info->>'myID'=alum::text and not(info->>'isAdmin')::boolean;
    assert club_private.can_listen_to_mailbox('mail:'||alum||':'||c) and not club_private.can_listen_to_mailbox('mail:'||alum||':'||other);
    begin perform public.snapshot(other::text); raise exception 'Secondary pending request bypassed isolation';
    exception when insufficient_privilege then null; end;
    perform public.send_message(c::text,owner,direct_message,'Club-specific alumni conversation');
    assert public.message_inbox(c::text)->0->>'peer'=owner::text;
    begin perform public.review_alumni_applications(c::text); raise exception 'Ordinary approved member saw private queue';
    exception when insufficient_privilege then null; end;
    perform public.save_alumni_profile('{"photoData":null,"bio":"Updated alum bio"}');
    assert public.alumni_workspace()->'profile'->'photoData'='null'::jsonb;
    assert exists(select from jsonb_array_elements(public.snapshot(c::text)->'members') x where x->>'id'=alum::text and x->>'bio'='Updated alum bio' and x->'photoData'='null'::jsonb);
    begin perform public.withdraw_alumni_request(c::text); raise exception 'Already-approved member withdrew acceptance';
    exception when invalid_parameter_value then null; end;
    select (x->>'id')::uuid into strict app from jsonb_array_elements(public.alumni_workspace()->'applications') x where x->>'clubID'=other::text;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
    assert jsonb_array_length(public.review_alumni_applications(other::text))=1;
    perform public.decide_alumni_application(other::text,app,false);
    perform set_config('request.jwt.claims',jsonb_build_object('sub',alum,'role','authenticated')::text,true);
    assert public.snapshot(c::text)->>'myID'=alum::text;
    begin perform public.snapshot(other::text); raise exception 'Independent decline granted content';
    exception when insufficient_privilege then null; end;
    perform public.request_alumni_membership(other::text,'Second club follow-up');
    select (x->>'id')::uuid into strict app from jsonb_array_elements(public.alumni_workspace()->'applications') x where x->>'clubID'=other::text;
    perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
    perform public.decide_alumni_application(other::text,app,true);
    perform set_config('request.jwt.claims',jsonb_build_object('sub',alum,'role','authenticated')::text,true);
    assert (select count(*) from jsonb_array_elements(public.club_catalog()) x where (x->>'joined')::boolean)=2;
    perform public.delete_account();
    perform set_config('request.jwt.claims',jsonb_build_object('sub',orphan,'role','authenticated')::text,true);
    perform public.save_alumni_profile('{"name":"No membership","graduationTerm":"spring","graduationYear":2001}');
    begin perform public.create_campus_club(gen_random_uuid(),'Subdomain user'); raise exception 'Subdomain account treated as campus';
    exception when insufficient_privilege then null; end;
    perform public.delete_account();
    reset role;
    assert not exists(select from auth.users where id in(alum,orphan));
    assert not exists(select from club_private.alumni_profiles where id in(alum,orphan));
    assert not exists(select from club_private.alumni_applications where applicant=alum);
    assert not exists(select from club_private.members where id=alum) and not exists(select from club_private.messages where id=direct_message);
    assert not has_table_privilege('authenticated','club_private.alumni_profiles','SELECT');
    assert not has_table_privilege('authenticated','club_private.alumni_applications','SELECT');
    assert not has_function_privilege('anon','public.alumni_workspace()','EXECUTE');
end $test$;
rollback;
